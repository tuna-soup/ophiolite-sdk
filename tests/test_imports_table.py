def test_map_pairs_parse_with_spaces_commas_and_lists():
    assert parse_mapping(['name=Formation,md=Top MD (m)', 'well=Well']) == {'name': 'Formation', 'md': 'Top MD (m)', 'well': 'Well'}
    assert parse_mapping(['attributes=porosity', 'attributes=perm,x=X']) == {'attributes': ['porosity', 'perm'], 'x': 'X'}
    with pytest.raises(Refused, match='FIELD=COLUMN'): parse_mapping(['name'])



def test_every_operation_the_imports_send_has_its_route():
    """The Fake answers without the client's route check; the real client refuses an operation it does not know
    (found by the C8 recipe against the in-process gateway: "Unsupported application operation.")."""
    from ophiolite.publish import operation_path
    operations = ('read', 'preview', 'start', 'step', 'status', 'pause', 'resume', 'cancel', 'list')
    assert [operation_path('p', 'table-imports', op) for op in operations] == ['/api/v1/projects/p/table-imports/' + op for op in operations]
