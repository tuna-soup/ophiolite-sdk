"""E87 C7: `client.imports.from_table` over the answers the Platform gave for the same file (the workspace's fixture
`app/tests/fixtures/table-import/answers.json`, copied byte-identically; generated by its `generate_answers.py`). The
words of the review and of the result equal the workspace's for F1 (R12); a dry run adds nothing; each refusal is said
in its J10 sentence with the service's own text kept as server_message."""
import json
from pathlib import Path

import pytest

from ophiolite.errors import CapacityExceeded, IntegrityConflict, PermissionRefused, Refused, VerificationFailed
from ophiolite.imports import (CHANGED, NOT_CHECKED, NOT_CONTRIBUTOR, UNREADABLE, Imports, parse_mapping, problem_words, result_lines,
                               review_lines, unit_problem_words)

A = json.loads((Path(__file__).parent / 'fixtures/table-import/answers.json').read_text())
TOPS = {'well': 'Well', 'name': 'Formation', 'md': 'Top MD (m)'}
ERRORS = {400: Refused, 403: PermissionRefused, 409: IntegrityConflict, 413: CapacityExceeded}


class Fake:
    """The client's two transports, answering from a scenario; a refusal is raised as the transport raises it."""
    project = 'p'

    def __init__(self, scenario, **over):
        self.a, self.over, self.sent, self.steps = A[scenario], over, [], 0

    def _answer(self, operation, body):
        self.sent.append((operation, body))
        answer = self.over.get(operation)
        if answer is None:
            if operation == 'step': self.steps += 1; answer = self.a['steps'][self.steps - 1]
            else: answer = self.a[operation]
        if 'status' in answer and 'body' in answer:
            raise ERRORS[answer['status']]('generic transport words', status=answer['status'], code=answer['body']['code'], server_message=answer['body']['error'])
        return answer

    def _post(self, area, operation, body, **options):
        assert area == 'table-imports' and options.get('retry') is True
        return self._answer(operation, body)

    def _post_bytes(self, area, operation, raw, *, extra_headers, **options):
        import base64
        meta = json.loads(base64.b64decode(extra_headers['X-Ophiolite-Upload']))
        assert (area, extra_headers['Content-Type'], meta['bytes']) == ('table-imports', 'application/octet-stream', len(raw))
        return self._answer(operation, {'upload': meta})


@pytest.fixture
def workbook(tmp_path):
    path = tmp_path / 'nlog-tops.xlsx'; path.write_bytes(b'PK not read here'); return path


def test_f1_lands_two_sets_in_the_workspace_words(workbook):
    fake = Fake('tops')
    done = Imports(fake).from_table(workbook, 'well-tops', TOPS)
    assert [s[0] for s in fake.sent] == ['read', 'preview', 'start', 'step']
    preview = fake.sent[1][1]
    assert (preview['target'], preview['input_id'], preview['mapping']) == ('well-tops', A['tops']['read']['input_id'],
                                                                           {'fields': TOPS, 'declarations': {}, 'schema_digest': A['tops']['read']['schema_digest']})
    assert fake.sent[2][1]['preview_digest'] == A['tops']['preview']['preview_digest'] and fake.sent[2][1]['audience'] == []
    # R12: the workspace's review lines and result rows (tests/table-import.mjs asserts the same literals in the browser)
    assert review_lines(done['preview']) == ['Tops to add: 2 sets (HON-GT-01: 24 rows, NLW-GT-01: 37 rows)', 'Already here: 0 sets', 'Skipped rows: 0',
                                             'Wells found: 1 of 2', 'Wells not found: NLW-GT-01. Its tops are added without a link to a well.',
                                             'This adds 2 of the 100 uploads left in this project.']
    assert result_lines(done['run'], done['preview']) == ['Finished', 'HON-GT-01 tops: Added: 24 tops, linked to well HON-GT-01',
                                                          'NLW-GT-01 tops: Added: 37 tops. No well named NLW-GT-01 was found, so these are not linked yet.']


def test_a_dry_run_reads_and_previews_and_adds_nothing(workbook):
    fake = Fake('tops')
    done = Imports(fake).from_table(workbook, 'well-tops', TOPS, dry_run=True)
    assert [s[0] for s in fake.sent] == ['read', 'preview'] and done['run'] is None  # mutation guard: a dry run that starts


def test_the_second_run_finds_both_sets_here(workbook):
    fake = Fake('again', read=A['tops']['read'])
    done = Imports(fake).from_table(workbook, 'well-tops', TOPS)
    assert review_lines(done['preview'])[:2] == ['Tops to add: 0 sets', 'Already here: 2 sets']
    assert result_lines(done['run'], done['preview'])[1:] == ['HON-GT-01 tops: Already here', 'NLW-GT-01 tops: Already here']


def test_skipped_rows_and_a_refused_series_in_words(tmp_path):
    review = Imports(Fake('skipping')).from_table(tmp_path / 'tops.csv', 'well-tops', TOPS, dry_run=True) if (tmp_path / 'tops.csv').write_text('x') else None
    assert review_lines(review['preview'])[2:5] == ['Skipped rows: 2', '  Row 3, Measured depth: "17x9.0" is not a number.', '  Row 4: no well.']
    survey = A['surveys']['preview']
    assert review_lines(survey)[3] == 'Not added: W-1: Row 3 has a depth that does not increase, so this series was not added. Fix the file and add it again.'
    assert problem_words({'row': 3, 'field': 'md', 'code': 'not-increasing', 'value': 90.0}, 'deviation-survey') == 'Row 3, Measured depth: "90" is not larger than in the row before.'
    assert unit_problem_words({'well': None, 'row': None, 'field': None, 'code': 'too-many-rows', 'value': 120000}, 'point-set') == \
        'The points for this table have 120,000 rows, more than Ophiolite adds in one set. Split the file.'


