"""E89 C6: `client.layouts()` and `imports.from_table(..., layout=)` over the answers the Platform gave (the workspace's
fixture `app/tests/fixtures/layouts/answers.json`, copied byte-identically; generated by its `generate_answers.py`). A
layout is named, never chosen for you: a table that matches one is refused with its name unless a mapping or the layout
is given; each refusal keeps the server's J7 sentence; the export is the bytes the workspace's Download saves."""
import base64
import hashlib
import json
from pathlib import Path

import pytest

from ophiolite.errors import IntegrityConflict, PermissionRefused, Refused, Unavailable
from ophiolite.imports import Imports
from ophiolite.layouts import Layouts, columns_line, export_bytes, import_lines, list_lines

A = json.loads((Path(__file__).parent / 'fixtures/layouts/answers.json').read_text())
ERRORS = {403: PermissionRefused, 404: Unavailable, 409: IntegrityConflict, 422: Refused}
DAY = '10 October 2026'
TUBBERGEN = A['listed']['layouts'][0]


class Fake:
    """The client's transports answering `area/operation` from the recorded answers (a list is answered in order); a
    refusal is raised as the transport raises it, with generic words and the server's sentence as server_message."""
    project = 'p'

    def __init__(self, **answers):
        self.answers, self.sent = {k: list(v) if isinstance(v, list) else v for k, v in answers.items()}, []

    def _answer(self, key, body):
        self.sent.append((key, body))
        answer = self.answers[key]
        if isinstance(answer, list): answer = answer.pop(0) if len(answer) > 1 else answer[0]
        if 'status' in answer and 'body' in answer:
            raise ERRORS[answer['status']]('generic transport words', status=answer['status'], code=answer['body']['code'], server_message=answer['body']['error'])
        return answer

    def _post(self, area, operation, body, **options):
        assert options.get('retry') is True
        return self._answer(area + '/' + operation, body)

    def _post_bytes(self, area, operation, raw, *, extra_headers, **options):
        meta = json.loads(base64.b64decode(extra_headers['X-Ophiolite-Upload']))
        return self._answer(area + '/' + operation, {'upload': meta})

    def layouts(self): return Layouts(self)

    @property
    def imports(self): return Imports(self)

    def members(self): return {'members': ['alice', 'bob', 'carol'], 'display': {'member_names': {'carol': 'Carol Smit', 'bob': 'Bram Jansen'}}}

    def keys(self): return [k for k, _ in self.sent]


def test_the_list_in_the_workspace_words():
    fake = Fake(**{'layouts/list': A['listed']})
    views = Layouts(fake).list()
    assert [(v['name'], v['made_by']) for v in views] == [('Tubbergen tops', 'carol')]
    assert columns_line(TUBBERGEN) == '4: Well Name, Top, MD (m) and 1 more'  # the file's order (mutation: the mapping's order fails)
    assert list_lines(views, {'carol': 'Carol Smit'}) == ['Tubbergen tops · Well tops · 4: Well Name, Top, MD (m) and 1 more · Made by Carol Smit, %s · Last used: Carol Smit, %s' % (DAY, DAY)]
    assert list_lines(views) == ['Tubbergen tops · Well tops · 4: Well Name, Top, MD (m) and 1 more · Made by a project member, %s · Last used: a project member, %s' % (DAY, DAY)]
    assert fake.sent == [('layouts/list', {'project_id': 'p'})]


def test_retired_layouts_are_left_out_when_asked_and_a_database_layout_says_so():
    assert Layouts(Fake(**{'layouts/list': A['listed_retired']})).list(retired=False) == []
    line, = list_lines(Layouts(Fake(**{'layouts/list': A['needs_connection']})).list())
    assert line.startswith('Groningen wells · Well locations (database table) · Made by a project member') and line.endswith('Not used yet · Needs its connection')


def test_match_lists_every_layout_and_says_another_order():
    layouts = Layouts(Fake(**{'layouts/match': [A['match_one'], A['match_reordered'], A['match_one']]}))
    assert [(m['name'], m['how']) for m in layouts.match(['Well Name', 'Top', 'MD (m)', 'TVD (m)'])] == [('Tubbergen tops', 'exact')]
    assert [(m['name'], m['how']) for m in layouts.match(['Top', 'Well Name', 'TVD (m)', 'MD (m)'])] == [('Tubbergen tops', 'reordered')]
    assert layouts.match(['Well Name'], target='wells') == []


def test_a_missing_name_is_j7_11_with_the_command_that_lists_them():
    with pytest.raises(Unavailable) as missing: Layouts(Fake(**{'layouts/list': A['listed']})).rename('Tubberge tops', 'x')
    assert str(missing.value) == 'This project has no layout called "Tubberge tops". List them with: ophiolite layouts list.'


def test_a_change_names_the_generation_it_read_and_a_refusal_keeps_its_sentence():
    fake = Fake(**{'layouts/list': A['listed'], 'layouts/rename': [A['renamed'], A['changed']]})
    layouts = Layouts(fake)
    assert layouts.rename('tubbergen  TOPS', 'Tubbergen tops 2026')['name'] == 'Tubbergen tops 2026'  # letter case and spacing aside
    sent = fake.sent[1][1]
    assert (sent['asset_id'], sent['expected_generation'], sent['new_name']) == (TUBBERGEN['asset_id'], 1, 'Tubbergen tops 2026') and sent['command_id']
    with pytest.raises(IntegrityConflict) as changed: layouts.rename('Tubbergen tops', 'Late')
    assert str(changed.value) == 'This layout changed after you opened it. Open it again to see the new version.' and changed.value.code == 'changed'


def test_save_keep_and_their_refusals():
    fake = Fake(**{'layouts/save': [A['saved'], A['name_taken'], A['viewer']], 'layouts/keep': [A['kept'], A['keep_nothing']]})
    layouts = Layouts(fake)
    fields = {'well': 'Well Name', 'name': 'Top', 'md': 'MD (m)'}
    assert layouts.save('well-tops', 'Tubbergen tops', ['Well Name', 'Top', 'MD (m)', 'TVD (m)'], fields, declarations={'depth_unit': 'm'})['version'] == 1
    assert fake.sent[0][1]['layout'] == {'target': 'well-tops', 'name': 'Tubbergen tops', 'columns': ['Well Name', 'Top', 'MD (m)', 'TVD (m)'],
                                         'mapping': {'fields': fields}, 'declarations': {'depth_unit': 'm'}, 'reading': {}}
    with pytest.raises(IntegrityConflict, match=r'^A layout called "tubbergen TOPS" already exists'): layouts.save('well-tops', 'x', ['a'], {})
    with pytest.raises(PermissionRefused, match='^Only people who can edit this project can change layouts'): layouts.save('well-tops', 'x', ['a'], {})
    assert layouts.keep('sql', 'w')['name'] == 'Groningen wells'
    assert {k: v for k, v in fake.sent[-1][1].items() if k != 'command_id'} == {'project_id': 'p', 'connection_id': 'sql', 'key': 'w'}  # no name: the server's
    with pytest.raises(IntegrityConflict, match='^You have not saved a mapping for this table yet'): layouts.keep('sql', 'w')


def test_export_is_the_bytes_the_workspace_downloads(tmp_path):
    fake = Fake(**{'layouts/export': A['export_one']})
    path = Layouts(fake).export_to(tmp_path / 'Tubbergen tops.layout.json', ['Tubbergen tops'])
    # sha256 of JSON.stringify(answer, null, 1) + '\n', computed with node outside the SDK (the browser's Download)
    assert hashlib.sha256(path.read_bytes()).hexdigest() == '9d0a9d23a8850186a36c49c8359fe5e3c3b716b7516695d3435ef37f7fbd001a'
    assert hashlib.sha256(export_bytes(A['export_all'])).hexdigest() == '0d08551054d822c990e963025534978f78583ef9ef44100b3135007565d71fc0'
    assert fake.sent[0][1] == {'project_id': 'p', 'names': ['Tubbergen tops']}


def test_import_says_one_outcome_per_layout(tmp_path):
    file = tmp_path / 'Other.layout.json'; file.write_text(json.dumps(A['import_file']))
    fake = Fake(**{'layouts/import': [A['imported'], A['not_a_file']]})
    answer = Layouts(fake).import_(file)
    assert fake.sent[0][1]['document'] == A['import_file']
    assert import_lines(answer) == ['Other tops: Already here', 'Imported tops: Added',
                                    'Bad tops: Not added: A layout in this file is not valid: the table kind is not supported. It was not added.']
    with pytest.raises(Refused, match=r'^This is not a layouts file from Ophiolite\. Choose a file made with "Download"\.$'): Layouts(fake).import_({'hello': 1})


def table(tmp_path):
    path = tmp_path / 'NLOG-tops-2.csv'; path.write_text('Well Name,Top,MD (m),TVD (m)\n'); return path


def landing(**over):
    return Fake(**{'table-imports/read': A['read'], 'layouts/list': A['listed'], 'layouts/match': A['match_one'], 'table-imports/preview': A['preview'],
                   'table-imports/start': A['started'], 'table-imports/step': A['stepped'], **over})


def test_a_named_layout_lands_with_its_mapping_and_is_recorded(tmp_path):
    fake = landing()
    done = Imports(fake).from_table(table(tmp_path), layout='Tubbergen tops')
    m = A['match_one']['matches'][0]
    preview = fake.sent[fake.keys().index('table-imports/preview')][1]
    assert (preview['target'], preview['layout'], preview['mapping']) == ('well-tops', {'id': m['asset_id'], 'version': 1, 'generation': 1},
                                                                         {'fields': m['fields'], 'declarations': {'depth_unit': 'm'}, 'schema_digest': A['read']['schema_digest']})
    start = fake.sent[fake.keys().index('table-imports/start')][1]
    assert start['layout'] == preview['layout'] and start['preview_digest'] == A['preview']['preview_digest']
    assert done['run']['state'] == 'complete' and done['run']['counts']['created'] == 1


def test_a_matching_layout_is_never_used_unless_named(tmp_path):
    fake = landing()
    with pytest.raises(IntegrityConflict) as needs: Imports(fake).from_table(table(tmp_path), 'well-tops')
    assert str(needs.value) == 'Needs your decision: this table matches the layout "Tubbergen tops". Add it with --layout "Tubbergen tops".'
    assert fake.keys() == ['table-imports/read', 'layouts/match']  # mutation guard: auto-apply previews and starts


def test_a_named_layout_that_does_not_fit_or_is_missing_lands_nothing(tmp_path):
    fake = landing(**{'layouts/match': A['match_none']})
    with pytest.raises(Refused, match='^This layout no longer fits this table: the columns differ'): Imports(fake).from_table(table(tmp_path), layout='Tubbergen tops')
    with pytest.raises(Unavailable, match='^This project has no layout called "Other"'): Imports(fake).from_table(table(tmp_path), layout='Other')
    assert 'table-imports/preview' not in fake.keys()
