KINDS = {inspect.Parameter.POSITIONAL_ONLY: '/', inspect.Parameter.POSITIONAL_OR_KEYWORD: '', inspect.Parameter.KEYWORD_ONLY: '*'}


def shape(cls, name):
    """The frozen form of one public attribute (see the module text)."""
    raw = inspect.getattr_static(cls, name)
    if isinstance(raw, property): return 'property'
    parts = []
    for p in inspect.signature(getattr(cls, name)).parameters.values():
        if p.name == 'self': continue
        if p.kind is p.VAR_POSITIONAL: text = '*' + p.name
        elif p.kind is p.VAR_KEYWORD: text = '**' + p.name
        else: text = KINDS[p.kind] + p.name
        if p.default is not p.empty: text += '=' + repr(p.default)
        parts.append(text)
    prefix = 'classmethod ' if isinstance(raw, classmethod) else 'staticmethod ' if isinstance(raw, staticmethod) else ''
    return prefix + ' '.join(parts)


