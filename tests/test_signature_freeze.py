@pytest.mark.parametrize('cls,frozen', [(Client, CLIENT), (CurveSet, CURVE_SET), (Wells, WELLS), (AsyncClient, ASYNC_CLIENT),
                                        (AsyncWorkFolder, ASYNC_WORK_FOLDER)],
                         ids=['Client', 'CurveSet', 'Wells', 'AsyncClient', 'AsyncWorkFolder'])
def test_every_frozen_call_keeps_its_parameters(cls, frozen):
    changed = {name: (want, shape(cls, name) if hasattr(cls, name) else 'missing') for name, want in frozen.items()
               if not hasattr(cls, name) or shape(cls, name) != want}
    assert changed == {}, 'parameters changed (frozen, now): %r' % changed


