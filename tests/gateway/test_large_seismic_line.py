"""E139 s4 C3 against the in-process gateway: a 2D line above 32 MiB (the generated 5,500 x 1,500 line, 34,323,600
bytes) uploads, describes and reads with its 5,500 trace positions; its original comes back by ranges and its digest
is the generated bytes'. Sync and async. No SDK source changes (D5)."""
import hashlib

import httpx
import pytest
from test_in_process_publish import web, shared, app, service, client  # noqa: F401 (fixtures)
from ophiolite import Credential
from project_gateway.tests.test_large_seismic_line import GEOMETRY, SIZE, line

MIB = 1024 * 1024
UPLOAD = dict(profile='segy-line/1', declared={'crs': 'EPSG:23031', 'z_domain': 'time'}, attribution='Synthetic', audience=[], rights_confirmed=True)
RANGES = ['bytes=%d-%d' % (i * 8 * MIB, (i + 1) * 8 * MIB - 1) for i in range(5)]  # the last range asks past the end, as the SDK does


@pytest.fixture
def requests(web, monkeypatch):
    monkeypatch.setenv('OPHIOLITE_MAX_FILE_BYTES', str(64 * MIB))
    log = []
    web.c.event_hooks['request'].append(lambda request: log.append((request.url.path, request.headers.get('range'))))
    return log


def check(got, described, raw):
    artifact = next(r for r in described['representations'] if r['id'] == 'artifact')
    assert (artifact['bytes'], artifact['sha256']) == (34_323_600, hashlib.sha256(raw).hexdigest())
    assert (got.type, got.context['traces'], got.context['samples'], len(got.geometry)) == ('seismic-line', 5500, 1500, 5500)
    assert {k: got.geometry[k] for k in GEOMETRY} == GEOMETRY
    assert got.original == raw and hashlib.sha256(got.original).hexdigest() == got.descriptor.revision


def test_a_line_above_32_mib_describes_and_reads_with_its_original_by_ranges(web, requests):
    """Mutation: the C2 describe gate reverted in the gateway (points-csv/1 only): describe answers 413, the SDK raises
    CapacityExceeded."""
    raw = line(); assert len(raw) == SIZE
    alice = client(web, 'alice', 'delegate')
    sent = alice.upload_data(raw, name='Large line', filename='large.sgy', **UPLOAD)
    assert sent.revision == hashlib.sha256(raw).hexdigest()
    requests.clear()
    described = alice._json(alice.prefix + '/' + sent.asset_id + '/revisions/' + sent.revision, 256 * 1024)
    got = alice.read_data(sent.asset_id, sent.revision)
    check(got, described, raw)
    assert [r for p, r in requests if r and p.endswith('/representations/artifact')] == RANGES


@pytest.fixture
def anyio_backend(): return 'asyncio'


@pytest.mark.anyio
async def test_the_async_client_reads_the_same_line(web, requests):
    """Mutation: as above (CapacityExceeded from AsyncClient.read_data)."""
    from ophiolite.aio import AsyncClient
    raw = line()
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app=web.app), base_url='https://workspace.example') as http:
        async with AsyncClient('https://workspace.example', 'p', Credential.bearer('oph_api_alice:read,write'), http) as alice:
            sent = await alice.upload_data(raw, name='Large line', filename='large.sgy', **UPLOAD)
            got = await alice.read_data(sent.asset_id, sent.revision)
    check(got, got._wire_descriptor, raw)
